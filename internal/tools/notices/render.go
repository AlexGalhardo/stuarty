const noticesFile = "THIRD_PARTY_NOTICES.md"

// managedDirs are the folders of licenses/ that the generator owns and
// rewrites completely. licenses/fonts and licenses/vendored are kept by hand
// and listed in the inventory.
var managedDirs = []string{"licenses/go-modules", "licenses/npm", "licenses/crates"}

// build collects every component, applies the allow-list and renders the
// output files, keyed by repository-relative slash path.
func build(ctx context.Context, run Runner, root string) (map[string][]byte, error) {
	goMods, err := goModules(ctx, run, root)
	if err != nil {
		return nil, err
	}

	npm, err := npmPackages(root)
	if err != nil {
		return nil, err
	}

	crates, err := rustCrates(ctx, run, root)
	if err != nil {
		return nil, err
	}

	inv, err := inventory(root)
	if err != nil {
		return nil, err
	}

	all := slices.Concat(goMods, npm, crates, inv)

	if err := checkAll(all); err != nil {
		return nil, err
	}

	files := map[string][]byte{}

	copied := slices.Concat(goMods, npm, crates)

	for ci := range copied {
		c := &copied[ci]

		for i, src := range c.Sources {
			raw, rerr := os.ReadFile(src)
			if rerr != nil {
				return nil, rerr
			}

			files[c.Licenses[i]] = bytes.ReplaceAll(raw, []byte("\r\n"), []byte("\n"))
		}
	}

	files[noticesFile] = []byte(render(all))

	return files, nil
}

// checkAll applies the allow-list to every component and reports all the
// violations at once, each naming its module or package (NFR-043).
func checkAll(all []Component) error {
	var errs []error

	for i := range all {
		if err := checkSPDX(all[i].SPDX, all[i].Group, all[i].Name); err != nil {
			errs = append(errs, err)
		}
	}

	return errors.Join(errs...)
}

var groupTitles = []struct{ group, title, intro string }{
	{groupGo, "Go modules", "Linked into the `vukem-video` binary, collected for the six release targets."},
	{
		groupNPM,
		"npm packages",
		"The production dependency closure of `web/package.json` (`dependencies`, transitively).",
	},
	{
		groupCrates,
		"Rust crates",
		"Compiled into the WebAssembly renderer of `renderer/` (`Cargo.lock`, normal dependencies of the wasm32 target; build-time proc macros are not shipped).",
	},
	{groupFonts, "Fonts", "Embedded in the binary; the rasterizer reads no other font."},
	{groupVendored, "Vendored code", "Source copied into this repository."},
	{
		groupPrograms,
		"External programs",
		"Run as separate processes; the archives do not carry FFmpeg, the image does.",
	},
}

// render writes THIRD_PARTY_NOTICES.md: deterministic, sorted, LF, no timestamp.
func render(all []Component) string {
	var b strings.Builder

	b.WriteString("# Third-party notices\n\n")
	b.WriteString(
		"Vukem Video is released under the [MIT licence](LICENSE.md). It includes or runs the third-party components below.\n",
	)
	b.WriteString(
		"This file is generated by `task notices` from the Go and npm dependencies and from `.config/third-party.json`; do not edit it by hand.\n",
	)
	b.WriteString("The text of each licence is under `licenses/`.\n")

	for _, g := range groupTitles {
		rows := slices.DeleteFunc(slices.Clone(all), func(c Component) bool { return c.Group != g.group })
		if len(rows) == 0 {
			continue
		}

		slices.SortFunc(rows, func(a, b Component) int {
			return cmp.Or(
				cmp.Compare(strings.ToLower(a.Name), strings.ToLower(b.Name)),
				cmp.Compare(a.Version, b.Version),
			)
		})

		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n", g.title, g.intro)
		b.WriteString(
			"| Name | Version | Licence | Copyright | Licence text | Notes |\n| --- | --- | --- | --- | --- | --- |\n",
		)

		for i := range rows {
			c := &rows[i]
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n",
				cell(c.Name), cell(c.Version), cell(c.SPDX), cell(c.Copyright), links(c.Licenses), cell(notes(*c)))
		}
	}

	b.WriteString("\n## Base image packages (Debian)\n\n")
	b.WriteString(
		"The container image is built on a Debian slim base. Its operating system packages are listed in `/usr/share/doc/vukem-video/base-image-packages.txt` inside the image, and the licence of each is the `copyright` file Debian keeps in `/usr/share/doc/<package>/`. They are an operating system, not part of the product: the product bundles and links no GPL component.\n",
	)

	return b.String()
}

func notes(c Component) string {
	var parts []string

	if c.Group == groupGo && strings.Contains(c.SPDX, "MPL-2.0") {
		parts = append(parts, "file-level copyleft: publish changes to its files")
	}

	if len(c.ShippedIn) > 0 {
		parts = append(parts, "shipped in: "+strings.Join(c.ShippedIn, ", "))
	} else if c.Group == groupPrograms {
		parts = append(parts, "not shipped: downloaded on first use")
	}

	if c.Note != "" {
		parts = append(parts, c.Note)
	}

	return strings.Join(parts, "; ")
}

// bareURL finds URLs that markdownlint (MD034) wants in angle brackets.
var bareURL = regexp.MustCompile(`https?://[^\s|)<>,]+`)

// bareEmail finds an e-mail address not already inside angle brackets; MD034
// flags it as a bare URL too. Group 1 is the character before it.
var bareEmail = regexp.MustCompile(`(^|[^<\w.+-])([\w.+-]+@[\w-]+(?:\.[\w-]+)+)`)

// obfuscated finds an angle-bracketed run with a space in it, such as
// "<name at host dot com>", which Markdown reads as an HTML tag.
var obfuscated = regexp.MustCompile(`<([^<>|]* [^<>|]*)>`)

var cellReplacer = strings.NewReplacer("|", `\|`, "\n", " ")

func cell(s string) string {
	if s == "" {
		return "-"
	}

	s = obfuscated.ReplaceAllString(cellReplacer.Replace(s), `\<$1\>`)
	s = bareURL.ReplaceAllString(s, "<$0>")

	return bareEmail.ReplaceAllString(s, "$1<$2>")
}

func links(paths []string) string {
	out := make([]string, len(paths))
	for i, p := range paths {
		out[i] = fmt.Sprintf("[%s](<%s>)", path.Base(p), p)
	}

	return strings.Join(out, ", ")
}

// write replaces the managed licence folders and the notices file.
func write(root string, files map[string][]byte) error {
	for _, d := range managedDirs {
		if err := os.RemoveAll(filepath.Join(root, filepath.FromSlash(d))); err != nil {
			return err
		}
	}

	for name, data := range files {
		full := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(full), 0o750); err != nil {
			return err
		}

		if err := os.WriteFile(full, data, 0o600); err != nil {
			return err
		}
	}

	return nil
}

// existing reads the files the generator owns from disk.
func existing(root string) (map[string][]byte, error) {
	out := map[string][]byte{}

	if raw, err := os.ReadFile(filepath.Join(root, noticesFile)); err == nil {
		out[noticesFile] = bytes.ReplaceAll(raw, []byte("\r\n"), []byte("\n"))
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}

	rootFS, err := os.OpenRoot(root)
	if err != nil {
		return nil, err
	}

	defer rootFS.Close()

	for _, d := range managedDirs {
		err := fs.WalkDir(rootFS.FS(), d, func(p string, e fs.DirEntry, werr error) error {
			if werr != nil {
				if errors.Is(werr, fs.ErrNotExist) {
					return nil
				}

				return werr
			}

			if e.IsDir() {
				return nil
			}

			raw, rerr := fs.ReadFile(rootFS.FS(), p)
			if rerr != nil {
				return rerr
			}

			out[p] = bytes.ReplaceAll(raw, []byte{13, 10}, []byte{10})

			return nil
		})
		if err != nil {
			return nil, err
		}
	}

	return out, nil
}

// diffFiles describes the difference between the committed files and the
// regenerated ones: a unified diff of the notices file and the list of
// licence files that are missing, extra or changed. It is empty when equal.
func diffFiles(have, want map[string][]byte) string {
	var b strings.Builder

	names := make([]string, 0, len(have)+len(want))
	for n := range have {
		names = append(names, n)
	}

	for n := range want {
		if _, ok := have[n]; !ok {
			names = append(names, n)
		}
	}

	slices.Sort(names)

	for _, n := range names {
		h, inHave := have[n]
		w, inWant := want[n]

		switch {
		case !inHave:
			fmt.Fprintf(&b, "missing: %s\n", n)
		case !inWant:
			fmt.Fprintf(&b, "extra: %s\n", n)
		case !bytes.Equal(h, w):
			if n == noticesFile {
				b.WriteString(unifiedDiff(n, string(h), string(w)))
			} else {
				fmt.Fprintf(&b, "changed: %s\n", n)
			}
		}
	}

	return b.String()
}

// unifiedDiff is a small line diff (longest common subsequence), enough to
// show a person what a regeneration would change.
func unifiedDiff(name, a, b string) string {
	x, y := strings.Split(a, "\n"), strings.Split(b, "\n")

	lcs := make([][]int, len(x)+1)
	for i := range lcs {
		lcs[i] = make([]int, len(y)+1)
	}

	for i, v := range slices.Backward(x) {
		for j := len(y) - 1; j >= 0; j-- {
			if v == y[j] {
				lcs[i][j] = lcs[i+1][j+1] + 1
			} else {
				lcs[i][j] = max(lcs[i+1][j], lcs[i][j+1])
			}
		}
	}

	var out strings.Builder

	fmt.Fprintf(&out, "--- %s (committed)\n+++ %s (generated)\n", name, name)

	lines := 0
	i, j := 0, 0

	emit := func(prefix, line string) {
		if lines < maxDiffLines {
			fmt.Fprintf(&out, "%s%s\n", prefix, line)
		}

		lines++
	}

	for i < len(x) || j < len(y) {
		switch {
		case i < len(x) && j < len(y) && x[i] == y[j]:
			i++
			j++
		case j < len(y) && (i == len(x) || lcs[i][j+1] >= lcs[i+1][j]):
			emit("+", y[j])
			j++
		default:
			emit("-", x[i])
			i++
		}
	}

	if lines > maxDiffLines {
		fmt.Fprintf(&out, "... %d more changed lines\n", lines-maxDiffLines)
	}

	return out.String()
}

const maxDiffLines = 80
