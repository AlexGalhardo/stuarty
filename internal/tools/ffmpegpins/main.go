// Command ffmpegpins writes internal/ffmpegpins/pins_gen.go from .config/ffmpeg.env: the SHA-256 of
// the pinned ffmpeg and ffprobe binaries of each platform, which `doctor --verify` compares with
// the bundled files (SDD-011 section 9). With -check it writes nothing and exits 1 when the file on
// disk differs from what the env file produces.
//
//	go run ./internal/tools/ffmpegpins -env .config/ffmpeg.env -out internal/ffmpegpins/pins_gen.go [-check]
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"slices"
	"strings"
)

var (
	hex64   = regexp.MustCompile(`^[0-9a-f]{64}$`)
	keyForm = regexp.MustCompile(`^(FFMPEG|FFPROBE)_BIN_SHA256_([A-Z0-9]+)_([A-Z0-9]+)$`)
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(argv []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("ffmpegpins", flag.ContinueOnError)
	fs.SetOutput(stderr)

	envPath := fs.String("env", ".config/ffmpeg.env", "the pin file")
	outPath := fs.String("out", "internal/ffmpegpins/pins_gen.go", "the generated Go file")
	check := fs.Bool("check", false, "fail when the generated file is not up to date; write nothing")

	if err := fs.Parse(argv); err != nil {
		return 2
	}

	// Both paths come from the command line of whoever runs the tool or from go:generate.
	in, err := os.ReadFile(*envPath)
	if err != nil {
		fmt.Fprintf(stderr, "ffmpegpins: %v\n", err)

		return 1
	}

	want, err := generate(in)
	if err != nil {
		fmt.Fprintf(stderr, "ffmpegpins: %s: %v\n", *envPath, err)

		return 1
	}

	if *check {
		have, err := os.ReadFile(*outPath)
		if err != nil || !bytes.Equal(have, want) {
			fmt.Fprintf(stderr, "ffmpegpins: %s is out of date; run go generate ./internal/ffmpegpins\n", *outPath)

			return 1
		}

		fmt.Fprintf(stdout, "ffmpegpins: %s is up to date\n", *outPath)

		return 0
	}

	if err := os.WriteFile(*outPath, want, 0o600); err != nil {
		fmt.Fprintf(stderr, "ffmpegpins: %v\n", err)

		return 1
	}

	return 0
}

// parseEnv reads KEY="value" lines; comments and blank lines are skipped.
func parseEnv(in []byte) (map[string]string, error) {
	vars := map[string]string{}

	for i, line := range strings.Split(string(in), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		k, v, ok := strings.Cut(line, "=")
		if !ok {
			return nil, fmt.Errorf("line %d: not KEY=value", i+1)
		}

		vars[strings.TrimSpace(k)] = strings.Trim(strings.TrimSpace(v), `"`)
	}

	return vars, nil
}

// collect groups the binary digests by "goos/goarch" and tool name.
func collect(vars map[string]string) (map[string]map[string]string, error) {
	pins := map[string]map[string]string{}

	for k, v := range vars {
		m := keyForm.FindStringSubmatch(k)
		if m == nil {
			continue
		}

		if !hex64.MatchString(v) {
			return nil, fmt.Errorf("%s is not 64 lowercase hex characters", k)
		}

		platform := strings.ToLower(m[2] + "/" + m[3])
		if pins[platform] == nil {
			pins[platform] = map[string]string{}
		}

		pins[platform][strings.ToLower(m[1])] = v
	}

	if len(pins) == 0 {
		return nil, errors.New("no FFMPEG_BIN_SHA256_* and FFPROBE_BIN_SHA256_* pair")
	}

	for p, tools := range pins {
		if tools["ffmpeg"] == "" || tools["ffprobe"] == "" {
			return nil, fmt.Errorf("platform %s needs both an FFMPEG and an FFPROBE digest", p)
		}
	}

	return pins, nil
}

// generate returns the formatted source of pins_gen.go for the contents of the env file.
func generate(in []byte) ([]byte, error) {
	vars, err := parseEnv(in)
	if err != nil {
		return nil, err
	}

	tag := vars["FFMPEG_RELEASE_TAG"]
	if tag == "" {
		return nil, errors.New("FFMPEG_RELEASE_TAG is missing")
	}

	pins, err := collect(vars)
	if err != nil {
		return nil, err
	}

	platforms := make([]string, 0, len(pins))
	for p := range pins {
		platforms = append(platforms, p)
	}

	slices.Sort(platforms)

	var b bytes.Buffer

	b.WriteString("// Code generated by internal/tools/ffmpegpins from .config/ffmpeg.env; DO NOT EDIT.\n\n")
	b.WriteString("package ffmpegpins\n\n")
	fmt.Fprintf(&b, "// Release is the FFMPEG_RELEASE_TAG the digests belong to.\nconst Release = %q\n\n", tag)
	b.WriteString("// table maps \"goos/goarch\" to the SHA-256 of the pinned ffmpeg and ffprobe binaries.\n")
	b.WriteString("var table = map[string]map[string]string{\n")

	for _, p := range platforms {
		fmt.Fprintf(&b, "%q: {\"ffmpeg\": %q, \"ffprobe\": %q},\n", p, pins[p]["ffmpeg"], pins[p]["ffprobe"])
	}

	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}

	return out, nil
}
