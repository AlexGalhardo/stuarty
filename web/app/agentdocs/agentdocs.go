// Package agentdocs is the material shipped for agents (SDD-003 section 8): the
// skill file, the AGENTS.md snippet and the MCP server instructions. They are
// generated from the command registry, the lint catalogue and the tables of
// data.go by cmd/gen-agent-docs, committed under out/ and embedded in the
// binary; the MCP server reads its instructions from the embedded copy.
package agentdocs

import (
	"embed"
	"fmt"
	"strings"
)

// Version is the version of the product the material describes, written into
// the header of every file and the frontmatter of the skill, and the one version
// every command of the binary reports (version, doctor, serve, the template and
// bundle files). The release commit bumps it and regenerates out/ (go run
// ./web/cmd/gen-agent-docs); every release build also stamps it with
// -X github.com/AlexGalhardo/stuarty/web/app/agentdocs.Version=<X.Y.Z>, so a
// binary never reports another version than the tag it was built from.
var Version = "0.29.0"

// The three artifacts of SDD-003 section 8.1.
const (
	SkillFile        = "SKILL.md"
	SnippetFile      = "AGENTS.snippet.md"
	InstructionsFile = "mcp-instructions.txt"
)

// Files lists the generated files in the order they are written.
var Files = []string{SkillFile, SnippetFile, InstructionsFile}

//go:embed out/*
var outFS embed.FS

// File returns one generated file as committed.
func File(name string) ([]byte, error) {
	b, err := outFS.ReadFile("out/" + name)
	if err != nil {
		return nil, fmt.Errorf("agentdocs: %w", err)
	}

	return b, nil
}

// Kinds maps the argument of `agent:docs --print` to its file.
var Kinds = map[string]string{"skill": SkillFile, "agents": SnippetFile, "instructions": InstructionsFile}

// Instructions is the text of the MCP server instructions: the generated file
// without its header line.
func Instructions() string {
	b, err := File(InstructionsFile)
	if err != nil {
		return ""
	}

	text := string(b)
	if strings.HasPrefix(text, "# generated by") {
		_, text, _ = strings.Cut(text, "\n")
	}

	return strings.TrimSpace(text)
}
