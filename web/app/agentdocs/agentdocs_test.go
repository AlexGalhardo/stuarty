var opGroupLine = regexp.MustCompile("(?m)^- `([a-z]+)`: ([a-z_*, ]+)$")

// checkOperations: the grouped list of the skill is exactly the public operations
// of the registry, alpha ones starred.
func checkOperations(t *testing.T, skill string) {
	t.Helper()

	listed := map[string]bool{}

	for _, m := range opGroupLine.FindAllStringSubmatch(skill, -1) {
		for a := range strings.SplitSeq(m[2], ", ") {
			listed[m[1]+"."+a] = true
		}
	}

	want := map[string]bool{}

	for _, c := range command.Default().List() {
		if c.Internal {
			continue
		}

		name := c.Name
		if c.Phase != command.Prototype {
			name += "*"
		}

		want[name] = true
	}

	for name := range want {
		if !listed[name] {
			t.Errorf("SKILL.md does not list the operation %s", name)
		}
	}

	for name := range listed {
		if !want[name] {
			t.Errorf("SKILL.md lists %s, which the registry does not have", name)
		}
	}
}

// fixedResolver hands every command the Service of a test environment.
type fixedResolver struct{ svc service.Service }

func (r fixedResolver) Resolve(context.Context, cli.Target) (*cli.Connection, error) {
	return &cli.Connection{Service: r.svc, Workspace: "/ws"}, nil
}

// splitCommand splits a command line on spaces, keeping a quoted part together
// without its quotes, as a shell does: a double quote and a single quote each
// close only with their own kind.
func splitCommand(line string) []string {
	var (
		args   []string
		cur    strings.Builder
		quote  rune
		quoted bool
	)

	for _, r := range line {
		switch {
		case quote == 0 && (r == '"' || r == '\''):
			quote, quoted = r, true
		case r == quote:
			quote = 0
		case r == ' ' && quote == 0:
			if quoted {
				args, cur, quoted = append(args, cur.String()), strings.Builder{}, false
			}
		default:
			cur.WriteRune(r)

			quoted = true
		}
	}

	if quoted {
		args = append(args, cur.String())
	}

	return args
}

// TestRecipesRun is SDD-003 section 8.2 item 4: every recipe of the skill is run
// as written, command by command, through the CLI over a real Service, and ends
// with the exit code it declares. A command that stops working breaks the build.
func TestRecipesRun(t *testing.T) {
	recipes, err := agentdocs.Recipes()
	if err != nil {
		t.Fatal(err)
	}

	if len(recipes) < 5 {
		t.Fatalf("%d recipes, want at least 5", len(recipes))
	}

	for _, r := range recipes {
		t.Run(r.Title, func(t *testing.T) {
			opts := testenv.Options{Transcriber: &testenv.StubTranscriber{Words: recipeWords}, SilenceBlocks: true}
			env := testenv.New(t, opts)
			env.WriteFile(t, "clip.mp4", strings.Repeat("v", 64))

			for i, step := range r.Steps {
				line := step.Cmd
				if step.Run != "" {
					line = step.Run
				}

				args := splitCommand(line)

				var stdout, stderr bytes.Buffer

				rt := &cli.Runtime{
					Stdin: strings.NewReader(step.Stdin), Stdout: &stdout, Stderr: &stderr,
					Getenv: func(string) string { return "" }, Getwd: func() (string, error) { return env.Files, nil },
					Resolver: fixedResolver{svc: env.Service},
				}

				if code := rt.Execute(t.Context(), args[0], args[1:]); code != step.Exit {
					t.Fatalf("step %d (%s): exit %d, want %d\n%s%s",
						i, line, code, step.Exit, stdout.String(), stderr.String())
				}
			}
		})
	}
}

// recipeWords are the words the stub transcriber returns to the recipes: two
// caption lines, with a silence between them.
var recipeWords = []transcribe.RawWord{
	{Text: "hello", StartMS: 100, EndMS: 400},
	{Text: "brave", StartMS: 400, EndMS: 700},
	{Text: "new", StartMS: 1100, EndMS: 1400},
	{Text: "world", StartMS: 1400, EndMS: 1900},
}

