func generated(t *testing.T) map[string][]byte {
	t.Helper()

	files, err := agentdocs.Generate(cli.AgentDocsInputs())
	if err != nil {
		t.Fatal(err)
	}

	return files
}

// TestAgentDocsGenerated: the committed files are what the generator produces,
// they stay inside the limits of SDD-003 section 8.1, and every name they use
// exists (a typo in a template fails here).
func TestAgentDocsGenerated(t *testing.T) {
	t.Parallel()

	files := generated(t)

	for _, name := range agentdocs.Files {
		have, err := agentdocs.File(name)
		if err != nil {
			t.Fatal(err)
		}

		if !bytes.Equal(have, files[name]) {
			t.Errorf("out/%s is stale: run go run ./web/cmd/gen-agent-docs", name)
		}

		if strings.Contains(string(have), "\n\n\n") {
			t.Errorf("out/%s has two blank lines in a row (markdownlint MD012)", name)
		}

		if !strings.Contains(string(have), "generated by vukem-video "+agentdocs.Version) {
			t.Errorf("out/%s has no generated header with the version", name)
		}
	}

	skill := string(files[agentdocs.SkillFile])

	if n := len([]rune(skill)); n > 12000 {
		t.Errorf("SKILL.md is %d characters, at most 12,000", n)
	}

	if !strings.Contains(skill, "metadata:\n  version: \""+agentdocs.Version+"\"") {
		t.Error("SKILL.md frontmatter has no metadata.version")
	}

	snippet := string(files[agentdocs.SnippetFile])
	begin := strings.Index(snippet, "<!-- vukem-video:begin -->")
	end := strings.Index(snippet, "<!-- vukem-video:end -->")

	if begin < 0 || end < begin {
		t.Fatal("the snippet has no begin and end markers")
	}

	if lines := strings.Count(snippet[begin:end], "\n") + 1; lines > 40 {
		t.Errorf("the snippet is %d lines, at most 40", lines)
	}

	if n := len(files[agentdocs.InstructionsFile]); n > 2100 {
		t.Errorf("mcp-instructions.txt is %d bytes, at most 2,100", n)
	}

	checkNames(t, skill)
}

var (
	opName   = regexp.MustCompile("`([a-z]+[.][a-z_]+)`")
	lintName = regexp.MustCompile("`(L_[A-Z_]+)`")
	cliLine  = regexp.MustCompile("(?m)^- `([a-z]+(?::[a-z]+)?)[ `]")
)

func checkNames(t *testing.T, skill string) {
	t.Helper()

	ops := command.Default().Names()

	for _, m := range opName.FindAllStringSubmatch(skill, -1) {
		// details.diff and details.reason are members of an error, not operations.
		if !slices.Contains(ops, m[1]) && !strings.HasPrefix(m[1], "details.") &&
			m[1] != "namespace.action" {
			t.Errorf("SKILL.md names the operation %s, which the registry does not have", m[1])
		}
	}

	checkOperations(t, skill)

	var codes []string
	for _, r := range lint.Catalog() {
		codes = append(codes, r.Code)
	}

	for _, m := range lintName.FindAllStringSubmatch(skill, -1) {
		if !slices.Contains(codes, m[1]) {
			t.Errorf("SKILL.md names the lint code %s, which the catalogue does not have", m[1])
		}
	}

	all, _ := cli.CommandNames()

	_, sheet, _ := strings.Cut(skill, "## CLI cheat sheet")
	sheet, _, _ = strings.Cut(sheet, "\n## ")

	for _, m := range cliLine.FindAllStringSubmatch(sheet, -1) {
		if !slices.Contains(all, m[1]) {
			t.Errorf("SKILL.md names the CLI command %s, which does not exist", m[1])
		}
	}

	for _, m := range regexp.MustCompile(`vukem-video ([a-z]+:[a-z]+|edit|lint|view|export|history|version|serve|mcp)`).
		FindAllStringSubmatch(skill, -1) {
		if m[1] != "serve" && !slices.Contains(all, m[1]) {
			t.Errorf("SKILL.md runs vukem-video %s, which does not exist", m[1])
		}
	}
}

// TestToolTable: every tool of the table is a tool of the server and the other
// way round, and every command it names exists.
func TestToolTable(t *testing.T) {
	t.Parallel()

	env := testenv.New(t, testenv.Options{})

	srv, err := mcp.New(env.Service, mcp.Options{})
	if err != nil {
		t.Fatal(err)
	}

	ct, st := sdk.NewInMemoryTransports()

	if _, err := srv.Connect(t.Context(), st, nil); err != nil {
		t.Fatal(err)
	}

	cs, err := sdk.NewClient(&sdk.Implementation{Name: "t", Version: "1"}, nil).Connect(t.Context(), ct, nil)
	if err != nil {
		t.Fatal(err)
	}

	defer func() { _ = cs.Close() }()

	list, err := cs.ListTools(t.Context(), nil)
	if err != nil {
		t.Fatal(err)
	}

	var tools []string
	for _, tool := range list.Tools {
		tools = append(tools, tool.Name)
	}

	all, _ := cli.CommandNames()

	var rows []string

	for _, r := range agentdocs.Tools {
		rows = append(rows, r.Tool)

		for _, c := range r.Commands {
			if !slices.Contains(all, c) {
				t.Errorf("the tool %s maps to %s, which is not a CLI command", r.Tool, c)
			}
		}
	}

	if !slices.Equal(rows, tools) {
		t.Errorf("tool table %v differs from the server %v", rows, tools)
	}
}

// TestErrorTable: every code of the core has a row, no row is repeated, and the
// status of a code the service maps is not the fallback 500 unless it is E_INTERNAL.
func TestErrorTable(t *testing.T) {
	t.Parallel()

	seen := map[string]bool{}

	for _, r := range agentdocs.Errors {
		if seen[r.Code] {
			t.Errorf("%s is listed twice", r.Code)
		}

		seen[r.Code] = true
	}

	for _, c := range command.Codes() {
		if !seen[c] {
			t.Errorf("the core code %s has no row", c)
		}
	}

	// The failures of a job are 500 in service.Error: their reason is in details.
	jobFailures := []string{
		"E_INTERNAL", "E_INGEST_FAILED", "E_EXPORT_FAILED", "E_VERIFY_FAILED", "E_TRANSCRIBE_FAILED", "E_CANCELLED",
	}

	for _, r := range agentdocs.Errors {
		if st := (&service.Error{Code: r.Code}).HTTPStatus(); st == 500 && !slices.Contains(jobFailures, r.Code) {
			t.Errorf("%s has no HTTP status in service.Error", r.Code)
		}
	}
}

