// TestGuideHasOnePagePerDomain: the guide is one page for each domain of SDD-000 section 1.1, the committed pages are
// what the generator writes now, and each page names what reaches its domain (epic 13).
func TestGuideHasOnePagePerDomain(t *testing.T) {
	t.Parallel()

	files := generated(t)

	if got, want := agentdocs.GuideFiles(), command.DomainNames(); len(got) != len(want) {
		t.Fatalf("%d pages for %d domains", len(got), len(want))
	}

	for _, d := range command.DomainNames() {
		name := agentdocs.GuideFile(d)

		have, err := agentdocs.Guide(d)
		if err != nil {
			t.Fatalf("the page of %s is not committed: %v", d, err)
		}

		if !bytes.Equal(have, files[name]) {
			t.Errorf("out/%s is stale: run go run ./web/cmd/gen-agent-docs", name)
		}

		text := string(have)

		if !strings.Contains(text, "# The "+d+" domain") || !strings.Contains(text, "generated by stuarty") {
			t.Errorf("%s: no title or no generated header", name)
		}

		if strings.Contains(text, "\n\n\n") {
			t.Errorf("%s has two blank lines in a row (markdownlint MD012)", name)
		}

		for _, tool := range mcp.ToolNames() {
			if slices.Contains(mcp.ToolDomains(tool), d) != strings.Contains(text, "`"+tool+"`") {
				t.Errorf(
					"%s: the tool %s belongs to the domain %v, and the page disagrees",
					name,
					tool,
					slices.Contains(mcp.ToolDomains(tool), d),
				)
			}
		}

		for _, c := range cli.Reference().Commands {
			if (cli.CommandDomain(c.Name) == d) != strings.Contains(text, "- `"+c.Name+"`:") {
				t.Errorf(
					"%s: the command %s is in the domain %s, and the page disagrees",
					name,
					c.Name,
					cli.CommandDomain(c.Name),
				)
			}
		}
	}

	if _, err := agentdocs.Guide("nope"); err == nil {
		t.Error("a page for a domain that does not exist")
	}
}

// The operations a page lists are the registry's, and a domain with none says so.
func TestGuideListsTheOperationsOfItsRegistry(t *testing.T) {
	t.Parallel()

	for domain, reg := range map[string]*command.Registry{command.DomainVideo: command.Default(), command.DomainImage: coreimage.Registry()} {
		page, err := agentdocs.Guide(domain)
		if err != nil {
			t.Fatal(err)
		}

		public := 0

		for _, c := range reg.List() {
			if c.Internal {
				continue
			}

			public++

			ns, action, _ := strings.Cut(c.Name, ".")
			if !strings.Contains(string(page), "`"+ns+"`: ") || !strings.Contains(string(page), action) {
				t.Errorf("%s: the page does not list %s", domain, c.Name)
			}
		}

		if !strings.Contains(string(page), fmt.Sprintf("These %d operations", public)) {
			t.Errorf("%s: the page does not say it has %d operations", domain, public)
		}
	}

	for _, domain := range []string{command.DomainWriting, command.DomainPublish, command.DomainProvider} {
		page, err := agentdocs.Guide(domain)
		if err != nil || !strings.Contains(string(page), "No edit operations yet") {
			t.Errorf("%s: %v, %q", domain, err, page)
		}
	}
}
