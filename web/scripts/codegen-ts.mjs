// Writes the TypeScript contracts of ADR-0014 into resources/js/generated/ from the
// JSON files that `go run ./internal/tools/contractgen` wrote under ../core/schema.
// Run it through `task codegen`; never edit the output by hand.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const schemaDir = join(root, "core", "schema");
const outDir = join(root, "web", "resources", "js", "generated");
const banner = "// Generated by task codegen (ADR-0014). Do not edit.\n";

const readJSON = async (name) => JSON.parse(await readFile(join(schemaDir, name), "utf8"));
const options = { bannerComment: banner, additionalProperties: false, format: true, strictIndexSignatures: false };
const pascal = (name) =>
	name
		.split(/[._]/)
		.map((p) => p[0].toUpperCase() + p.slice(1))
		.join("");

await mkdir(outDir, { recursive: true });

// timeline.ts: the document and every type it holds.
const timeline = await readJSON("timeline.v1.schema.json");
const { $schema, $id, ...document } = timeline;
await writeFile(
	join(outDir, "timeline.ts"),
	await compile({ ...document, title: "ProjectDocument" }, "ProjectDocument", options),
);

// commands.ts: one args type per command, the names, the map and the operation type.
const commands = await readJSON("commands.json");
let ts = banner;
for (const c of commands) {
	const { $schema: _s, ...args } = c.args_schema;
	const type = await compile({ ...args, title: `${pascal(c.name)}Args` }, `${pascal(c.name)}Args`, {
		...options,
		bannerComment: "",
	});
	ts += `\n${type}`;
}
ts += `\nexport type CommandName = ${commands.map((c) => JSON.stringify(c.name)).join(" | ")};\n`;
ts += `\nexport interface CommandArgsMap {\n${commands.map((c) => `\t${JSON.stringify(c.name)}: ${pascal(c.name)}Args;`).join("\n")}\n}\n`;
ts += "\nexport type Operation = { [K in CommandName]: { op: K; args: CommandArgsMap[K] } }[CommandName];\n";
ts += `\nexport const COMMANDS: Record<CommandName, { summary: string; scope: "edit" | "media"; internal: boolean; errors: ErrorCode[] }> = {\n`;
ts += commands
	.map(
		(c) =>
			`\t${JSON.stringify(c.name)}: { summary: ${JSON.stringify(c.summary)}, scope: ${JSON.stringify(c.scope)}, internal: ${c.internal}, errors: ${JSON.stringify(c.errors)} },`,
	)
	.join("\n");
ts += "\n};\n";
ts = `${ts.split("\n")[0]}\nimport type { ErrorCode } from "./errors";\n${ts.split("\n").slice(1).join("\n")}`;
await writeFile(join(outDir, "commands.ts"), ts);

// commands.json: the registry snapshot the UI coverage test reads.
await writeFile(join(outDir, "commands.json"), `${JSON.stringify(commands, null, "\t")}\n`);

// errors.ts and limits.ts.
const errors = await readJSON("errors.json");
await writeFile(
	join(outDir, "errors.ts"),
	`${banner}\nexport type ErrorCode = ${errors.map((e) => JSON.stringify(e.code)).join(" | ")};\n\n` +
		`export const ERROR_TABLE: Record<ErrorCode, { retryable: boolean; http: number }> = {\n` +
		errors.map((e) => `\t${e.code}: { retryable: ${e.retryable}, http: ${e.http} },`).join("\n") +
		"\n};\n",
);
// lint-rules.ts: the rule table of core/lint (SDD-003 section 3.6).
const lintRules = await readJSON("lint-rules.json");
await writeFile(
	join(outDir, "lint-rules.ts"),
	`${banner}
export type LintCode = ${lintRules.map((r) => JSON.stringify(r.code)).join(" | ")};

` +
		`export interface LintRule {
	code: LintCode;
	severity: "error" | "warning";
	depth: ("doc" | "item" | "full")[];
	blocking: boolean;
	key: string;
}

` +
		`export const LINT_RULES: LintRule[] = ${JSON.stringify(lintRules, null, "	")};
`,
);
// project-schema.ts: the JSON Schema of the context of a project, exported by z from core/project; the project
// form builds its zod schema from it, so the two never drift (epic 56).
const projectSchema = await readJSON("project.v1.schema.json");
await writeFile(
	join(outDir, "project-schema.ts"),
	`${banner}
export const PROJECT_SCHEMA = ${JSON.stringify(projectSchema, null, "	")} as const;
`,
);
const limits = await readJSON("limits.json");
await writeFile(
	join(outDir, "limits.ts"),
	`${banner}\nexport const LIMITS = {\n${Object.entries(limits)
		.map(([k, v]) => `\t${k}: ${v},`)
		.join("\n")}\n} as const;\n`,
);
