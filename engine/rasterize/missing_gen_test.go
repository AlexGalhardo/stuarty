const coverageFile = "coverage_gen.go"

func renderCoverage(t *testing.T) []byte {
	t.Helper()

	var b bytes.Buffer

	b.WriteString("// Code generated by go test ./engine/rasterize -run TestBundledCoverage -update; DO NOT EDIT.\n\n")
	b.WriteString("package rasterize\n\n")
	b.WriteString("// bundledCoverage is, per bundled family, the runes its font file has a glyph for, as sorted closed ranges.\n")
	b.WriteString("var bundledCoverage = map[string][][2]rune{\n")

	for _, f := range bundledFamilies {
		data, err := os.ReadFile(filepath.Join(fontDir, f.file))
		if err != nil {
			t.Fatal(err)
		}

		ranges, err := coverageRanges(data)
		if err != nil {
			t.Fatalf("%s: %v", f.file, err)
		}

		fmt.Fprintf(&b, "\t%q: {", f.name)

		for i, r := range ranges {
			if i > 0 {
				b.WriteString(", ")
			}

			fmt.Fprintf(&b, "{0x%x, 0x%x}", r[0], r[1])
		}

		b.WriteString("},\n")
	}

	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}

	return out
}

// TestBundledCoverage keeps the table of coverage_gen.go in step with the font files the module embeds.
func TestBundledCoverage(t *testing.T) {
	want := renderCoverage(t)

	if *update {
		if err := os.WriteFile(coverageFile, want, 0o600); err != nil {
			t.Fatal(err)
		}

		return
	}

	got, err := os.ReadFile(coverageFile)
	if err != nil {
		t.Fatal(err)
	}

	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatal("coverage_gen.go is stale: go test ./engine/rasterize -run TestBundledCoverage -update")
	}
}

func TestMissing(t *testing.T) {
	t.Parallel()

	cases := []struct {
		name, family, text string
		want               string
	}{
		{"latin with accents", "Inter", "Olá, mundo — ok", ""},
		{"cjk and emoji", "Inter", "Olá 日本 😀", "日本😀"},
		{"once each, in order", "Montserrat", "日日本日", "日本"},
		{"format characters are not reported", "Inter", "a\u200db\u200e\nc", ""},
		{"emoji selector is not reported", "Inter", "\ufe0f", ""},
		{"a static font", "Anton", "Hi 日", "日"},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel()

			got, err := Bundled().Missing(c.family, 400, c.text)
			if err != nil {
				t.Fatal(err)
			}

			if string(got) != c.want {
				t.Fatalf("Missing = %q, want %q", string(got), c.want)
			}
		})
	}

	if _, err := Bundled().Missing("Nope", 400, "a"); err == nil {
		t.Fatal("an unknown family must be an error")
	}

	// Every rune the lint calls missing is really drawn as the notdef box.
	if m, _ := Bundled().Missing("Inter", 400, "ab"); slices.Contains(m, 'a') {
		t.Fatal("a is in Inter")
	}

}
